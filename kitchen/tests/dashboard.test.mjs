assert.equal(model.priceOn(sample,records,[],model.addDays(today,1),today).price,43);
assert.equal(model.forecast(sample,[records[2]],[],model.addDays(today,1),today).price,42,'Sparse history stays flat');
assert.match(model.forecast(sample,[records[2]],[],model.addDays(today,1),today).method,/insufficient/);
assert.equal(model.latest(sample,records,[{...records[2],price:39,source:'Supplier quote'}],today).price,39);
assert.equal(model.priceTone(39,40),'cheap');assert.equal(model.priceTone(41,40),'expensive');assert.equal(model.priceTone(40,40),'neutral');assert.equal(model.priceTone(null,40),'neutral');
