import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import * as model from '../model.js';
import {defaults} from '../seed.js';
const today=model.todayIST();
const sample={name:'Tomato',unit:'kg'};
const records=[0,1,2].map((n)=>({...sample,date:model.addDays(today,n-2),price:40+n,source:'Test market',basis:'Retail'}));
assert.equal(model.priceOn(sample,records,[],model.addDays(today,-5),today),null,'Never invent history');
assert.equal(model.priceOn(sample,records,[],today,today).price,42);
assert.equal(model.priceOn(sample,records,[],model.addDays(today,1),today).price,43);
assert.equal(model.forecast(sample,[records[2]],[],model.addDays(today,1),today).price,42,'Sparse history stays flat');
assert.match(model.forecast(sample,[records[2]],[],model.addDays(today,1),today).method,/insufficient/);
assert.equal(model.latest(sample,records,[{...records[2],price:39,source:'Supplier quote'}],today).price,39);
assert.equal(model.priceTone(39,40),'cheap');assert.equal(model.priceTone(41,40),'expensive');assert.equal(model.priceTone(40,40),'neutral');assert.equal(model.priceTone(null,40),'neutral');
const dom=new JSDOM(readFileSync('kitchen/index.html','utf8'),{url:'https://example.org',runScripts:'outside-only'});
const w=dom.window;
w.defaults=defaults;Object.assign(w,model);w.setInterval=()=>0;
const feed=JSON.parse(readFileSync('kitchen/prices.json','utf8'));
w.fetch=async()=>({ok:true,json:async()=>feed});
const app=readFileSync('kitchen/app.js','utf8').replace(/^import .*;\n/gm,'');
w.eval(app);await new Promise(r=>setTimeout(r,0));
const $=s=>w.document.querySelector(s);
assert.equal(w.document.querySelectorAll('#rows tr').length,46);
assert.equal(w.document.querySelectorAll('#chart .day-card').length,7);
const q=$('[aria-label="Sona Masuri rice (raw) weekly quantity in kg"]');q.value=100;q.dispatchEvent(new w.Event('change'));
assert.equal($('#total').textContent,'₹6,000');assert.equal($('#allowance').textContent,'₹6,600');
const date=$('#priceDate');date.value='2026-01-01';date.dispatchEvent(new w.Event('change'));assert.equal($('#total').textContent,'₹0');assert.equal($('#missing').textContent,'46');
$('#today').click();
const target=$('[aria-label="Sona Masuri rice (raw) target price"]');target.value=70;target.dispatchEvent(new w.Event('change'));assert.ok($('#rows tr .price-value').classList.contains('cheap'));
$('#chart .day-card').click();assert.ok($('#viewLabel').textContent.startsWith('Projected'));assert.ok($('#rows tr td:last-child input').disabled);
assert.equal(JSON.parse(w.localStorage.getItem('kitchen-ledger-v2')).items[0].qty,100);
console.log('PASS: history, 7-day trend, flat fallback, quote priority, colours, date filtering, budgeting, persistence, future quote protection');
